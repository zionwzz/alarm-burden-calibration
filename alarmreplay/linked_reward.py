"""Linked-reward calibration: the estimator used for both the simulation and the application.

The observed data are replayed excursions and a recorded annunciation log. Linking the two makes the
reward of an excursion observed for *every* excursion, including excursions with no alarm assigned under the linkage convention, whose
linked seconds are observed zero rather than missing. Write

    Y_ij  = total linked annunciation seconds of excursion j of patient i   (Y = 0 when unlinked),
    a_0   = E(Y | D = d, Z = z)                                            at the limit in force,
    B_m(u) = int a_0(d, z) nu_u(dd, dz)                                    the linked burden under u,

where nu_u is the excursion mean measure generated by limit u. `a_0` is identified at the limit in
force; `B_m(u)` for a candidate limit u is identified under the transport and support conditions the
manuscript states.

Estimation is by cells. The cell map partitions duration (and optionally a feature such as overshoot)
into finitely many cells fixed before estimation. Each cell carries its own **carrier**:

    short cells   a nominal duration bin, carrier R = excursion count,
                  so beta_c = E(S_ic) / E(R_ic) is linked seconds per excursion (units s);
    pooled cells  a range of durations per cell, carrier R = replayed duration seconds,
                  so beta_c = E(S_ic) / E(R_ic) is the annunciation ratio (dimensionless).

For every cell, `beta_c * R_c(u)` is in seconds, so the standardized burden

    Bhat_m(u) = sum_c beta_c R_c(u)

is a sum of linked seconds whatever the carrier. Its fixed-map target is the cell-standardised
functional, which equals the scientific transported burden only under the stated within-cell
and coarsening conditions. This is the generic-carrier form: a single smooth
functional of patient-level sums, which is what makes the delta method and the patient-cluster
bootstrap apply to the estimator that is actually computed.

Everything here operates on arrays already summed within a patient, so a bootstrap replicate is a
resample of patient rows followed by a sum: `estimate(...)` is the same function of the patient means
in every replicate.
"""
from __future__ import annotations

